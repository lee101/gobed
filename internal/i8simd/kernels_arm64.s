// SDOT Vd.4S, Vn.16B, Vm.16B encodes as 0x4E809400 | Rm<<16 | Rn<<5 | Rd.

// func dot512SDOT(a, b *[512]int8) int32
TEXT ·dot512SDOT(SB), NOSPLIT, $0-20
	MOVD a+0(FP), R0
	MOVD b+8(FP), R1
	VEOR V0.B16, V0.B16, V0.B16
	VEOR V1.B16, V1.B16, V1.B16
	VEOR V2.B16, V2.B16, V2.B16
	VEOR V3.B16, V3.B16, V3.B16
	MOVD $8, R2
dotloop:
	VLD1.P 64(R0), [V4.B16, V5.B16, V6.B16, V7.B16]
	VLD1.P 64(R1), [V16.B16, V17.B16, V18.B16, V19.B16]
	WORD $0x4E909480 // SDOT V0.4S, V4.16B, V16.16B
	WORD $0x4E9194A1 // SDOT V1.4S, V5.16B, V17.16B
	WORD $0x4E9294C2 // SDOT V2.4S, V6.16B, V18.16B
	WORD $0x4E9394E3 // SDOT V3.4S, V7.16B, V19.16B
	SUBS $1, R2, R2
	BNE dotloop
	VADD V1.S4, V0.S4, V0.S4
	VADD V3.S4, V2.S4, V2.S4
	VADD V2.S4, V0.S4, V0.S4
	VADDV V0.S4, V0
	VMOV V0.S[0], R3
	MOVW R3, ret+16(FP)
	RET

// func centeredBlocks32(a, b *uint8, n int) (dot, na, nb int32)
// x^0x80 maps uint8 x to the int8 value x-128.
TEXT ·centeredBlocks32(SB), NOSPLIT, $0-36
	MOVD a+0(FP), R0
	MOVD b+8(FP), R1
	MOVD n+16(FP), R2
	VMOVI $128, V31.B16
	VEOR V4.B16, V4.B16, V4.B16
	VEOR V5.B16, V5.B16, V5.B16
	VEOR V6.B16, V6.B16, V6.B16
	VEOR V7.B16, V7.B16, V7.B16
	VEOR V8.B16, V8.B16, V8.B16
	VEOR V9.B16, V9.B16, V9.B16
cloop:
	VLD1.P 32(R0), [V0.B16, V1.B16]
	VLD1.P 32(R1), [V2.B16, V3.B16]
	VEOR V31.B16, V0.B16, V0.B16
	VEOR V31.B16, V1.B16, V1.B16
	VEOR V31.B16, V2.B16, V2.B16
	VEOR V31.B16, V3.B16, V3.B16
	WORD $0x4E829404 // SDOT V4.4S, V0.16B, V2.16B
	WORD $0x4E839425 // SDOT V5.4S, V1.16B, V3.16B
	WORD $0x4E809406 // SDOT V6.4S, V0.16B, V0.16B
	WORD $0x4E819427 // SDOT V7.4S, V1.16B, V1.16B
	WORD $0x4E829448 // SDOT V8.4S, V2.16B, V2.16B
	WORD $0x4E839469 // SDOT V9.4S, V3.16B, V3.16B
	SUBS $1, R2, R2
	BNE cloop
	VADD V5.S4, V4.S4, V4.S4
	VADD V7.S4, V6.S4, V6.S4
	VADD V9.S4, V8.S4, V8.S4
	VADDV V4.S4, V4
	VADDV V6.S4, V6
	VADDV V8.S4, V8
	VMOV V4.S[0], R3
	VMOV V6.S[0], R4
	VMOV V8.S[0], R5
	MOVW R3, dot+24(FP)
	MOVW R4, na+28(FP)
	MOVW R5, nb+32(FP)
	RET

// func accumS8(acc *int32, row *int8, n int)
TEXT ·accumS8(SB), NOSPLIT, $0-24
	MOVD acc+0(FP), R0
	MOVD row+8(FP), R1
	MOVD n+16(FP), R2
aloop:
	VLD1.P 16(R1), [V0.B16]
	VLD1 (R0), [V16.S4, V17.S4, V18.S4, V19.S4]
	VSXTL V0.B8, V1.H8
	VSXTL2 V0.B16, V2.H8
	VSXTL V1.H4, V3.S4
	VSXTL2 V1.H8, V4.S4
	VSXTL V2.H4, V5.S4
	VSXTL2 V2.H8, V6.S4
	VADD V3.S4, V16.S4, V16.S4
	VADD V4.S4, V17.S4, V17.S4
	VADD V5.S4, V18.S4, V18.S4
	VADD V6.S4, V19.S4, V19.S4
	VST1.P [V16.S4, V17.S4, V18.S4, V19.S4], 64(R0)
	SUBS $1, R2, R2
	BNE aloop
	RET

// func accumRows64(acc *int32, base *int8, offs *int, ntok int, nblk int)
// For each 64-wide column block, sums the int8 rows base[offs[t]+blk*64:]
// for t < ntok in eight int16x8 registers (exact for ntok <= 256), then
// widens once and adds into acc. Avoids a load/store of acc per row.
TEXT ·accumRows64(SB), NOSPLIT, $0-40
	MOVD acc+0(FP), R0
	MOVD base+8(FP), R1
	MOVD offs+16(FP), R2
	MOVD ntok+24(FP), R3
	MOVD nblk+32(FP), R4
	MOVD $0, R5
blk:
	VEOR V0.B16, V0.B16, V0.B16
	VEOR V1.B16, V1.B16, V1.B16
	VEOR V2.B16, V2.B16, V2.B16
	VEOR V3.B16, V3.B16, V3.B16
	VEOR V4.B16, V4.B16, V4.B16
	VEOR V5.B16, V5.B16, V5.B16
	VEOR V6.B16, V6.B16, V6.B16
	VEOR V7.B16, V7.B16, V7.B16
	MOVD R2, R6
	MOVD R3, R7
tok:
	MOVD.P 8(R6), R8
	ADD R1, R8, R8
	ADD R5, R8, R8
	VLD1 (R8), [V16.B16, V17.B16, V18.B16, V19.B16]
	VSXTL V16.B8, V20.H8
	VSXTL2 V16.B16, V21.H8
	VSXTL V17.B8, V22.H8
	VSXTL2 V17.B16, V23.H8
	VSXTL V18.B8, V24.H8
	VSXTL2 V18.B16, V25.H8
	VSXTL V19.B8, V26.H8
	VSXTL2 V19.B16, V27.H8
	VADD V20.H8, V0.H8, V0.H8
	VADD V21.H8, V1.H8, V1.H8
	VADD V22.H8, V2.H8, V2.H8
	VADD V23.H8, V3.H8, V3.H8
	VADD V24.H8, V4.H8, V4.H8
	VADD V25.H8, V5.H8, V5.H8
	VADD V26.H8, V6.H8, V6.H8
	VADD V27.H8, V7.H8, V7.H8
	SUBS $1, R7, R7
	BNE tok

	VLD1 (R0), [V16.S4, V17.S4, V18.S4, V19.S4]
	VSXTL V0.H4, V20.S4
	VSXTL2 V0.H8, V21.S4
	VSXTL V1.H4, V22.S4
	VSXTL2 V1.H8, V23.S4
	VADD V20.S4, V16.S4, V16.S4
	VADD V21.S4, V17.S4, V17.S4
	VADD V22.S4, V18.S4, V18.S4
	VADD V23.S4, V19.S4, V19.S4
	VST1.P [V16.S4, V17.S4, V18.S4, V19.S4], 64(R0)

	VLD1 (R0), [V16.S4, V17.S4, V18.S4, V19.S4]
	VSXTL V2.H4, V20.S4
	VSXTL2 V2.H8, V21.S4
	VSXTL V3.H4, V22.S4
	VSXTL2 V3.H8, V23.S4
	VADD V20.S4, V16.S4, V16.S4
	VADD V21.S4, V17.S4, V17.S4
	VADD V22.S4, V18.S4, V18.S4
	VADD V23.S4, V19.S4, V19.S4
	VST1.P [V16.S4, V17.S4, V18.S4, V19.S4], 64(R0)

	VLD1 (R0), [V16.S4, V17.S4, V18.S4, V19.S4]
	VSXTL V4.H4, V20.S4
	VSXTL2 V4.H8, V21.S4
	VSXTL V5.H4, V22.S4
	VSXTL2 V5.H8, V23.S4
	VADD V20.S4, V16.S4, V16.S4
	VADD V21.S4, V17.S4, V17.S4
	VADD V22.S4, V18.S4, V18.S4
	VADD V23.S4, V19.S4, V19.S4
	VST1.P [V16.S4, V17.S4, V18.S4, V19.S4], 64(R0)

	VLD1 (R0), [V16.S4, V17.S4, V18.S4, V19.S4]
	VSXTL V6.H4, V20.S4
	VSXTL2 V6.H8, V21.S4
	VSXTL V7.H4, V22.S4
	VSXTL2 V7.H8, V23.S4
	VADD V20.S4, V16.S4, V16.S4
	VADD V21.S4, V17.S4, V17.S4
	VADD V22.S4, V18.S4, V18.S4
	VADD V23.S4, V19.S4, V19.S4
	VST1.P [V16.S4, V17.S4, V18.S4, V19.S4], 64(R0)

	ADD $64, R5, R5
	SUBS $1, R4, R4
	BNE blk
	RET

// func finishU8(out *uint8, acc *int32, n int, inv, scale float32)
// out[i] = uint8(clamp(((float32(acc[i])*inv)/scale + 1) * 127.5, 0, 255))
// for n (>0) blocks of 16. Same IEEE float32 ops, same order, as the scalar
// C/Go code, so results are bit-identical; truncation toward zero.
TEXT ·finishU8(SB), NOSPLIT, $0-32
	MOVD out+0(FP), R0
	MOVD acc+8(FP), R1
	MOVD n+16(FP), R2
	FMOVS inv+24(FP), F24
	FMOVS scale+28(FP), F25
	VDUP V24.S[0], V24.S4
	VDUP V25.S[0], V25.S4
	FMOVS $1.0, F26
	VDUP V26.S[0], V26.S4
	MOVW $0x42FF0000, R3 // 127.5
	VDUP R3, V27.S4
	MOVW $0x437F0000, R3 // 255.0
	VDUP R3, V28.S4
	VEOR V29.B16, V29.B16, V29.B16 // 0.0
floop:
	VLD1.P 64(R1), [V0.S4, V1.S4, V2.S4, V3.S4]
	VSCVTF V0.S4, V0.S4
	VSCVTF V1.S4, V1.S4
	VSCVTF V2.S4, V2.S4
	VSCVTF V3.S4, V3.S4
	VFMUL V24.S4, V0.S4, V0.S4
	VFMUL V24.S4, V1.S4, V1.S4
	VFMUL V24.S4, V2.S4, V2.S4
	VFMUL V24.S4, V3.S4, V3.S4
	VFDIV V25.S4, V0.S4, V0.S4
	VFDIV V25.S4, V1.S4, V1.S4
	VFDIV V25.S4, V2.S4, V2.S4
	VFDIV V25.S4, V3.S4, V3.S4
	VFADD V26.S4, V0.S4, V0.S4
	VFADD V26.S4, V1.S4, V1.S4
	VFADD V26.S4, V2.S4, V2.S4
	VFADD V26.S4, V3.S4, V3.S4
	VFMUL V27.S4, V0.S4, V0.S4
	VFMUL V27.S4, V1.S4, V1.S4
	VFMUL V27.S4, V2.S4, V2.S4
	VFMUL V27.S4, V3.S4, V3.S4
	VFMAX V29.S4, V0.S4, V0.S4
	VFMAX V29.S4, V1.S4, V1.S4
	VFMAX V29.S4, V2.S4, V2.S4
	VFMAX V29.S4, V3.S4, V3.S4
	VFMIN V28.S4, V0.S4, V0.S4
	VFMIN V28.S4, V1.S4, V1.S4
	VFMIN V28.S4, V2.S4, V2.S4
	VFMIN V28.S4, V3.S4, V3.S4
	VFCVTZU V0.S4, V0.S4
	VFCVTZU V1.S4, V1.S4
	VFCVTZU V2.S4, V2.S4
	VFCVTZU V3.S4, V3.S4
	VXTN V0.S4, V4.H4
	VXTN2 V1.S4, V4.H8
	VXTN V2.S4, V5.H4
	VXTN2 V3.S4, V5.H8
	VXTN V4.H8, V6.B8
	VXTN2 V5.H8, V6.B16
	VST1.P [V6.B16], 16(R0)
	SUBS $1, R2, R2
	BNE floop
	RET
